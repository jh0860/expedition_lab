import test from "node:test";
import assert from "node:assert/strict";
import {createGame, applyAction, loadGame} from "../src/game.js";
import {cards} from "../src/content.js";

for (const [id, amount] of [["barter",1],["alchemy",2],["preciousCache",5]]) {
  test(`${id} generates persistent carried treasure and remains reusable`, () => {
    let s = createGame();
    s.players[0].hand = [id];
    s = applyAction(s,{type:"play",index:0});
    assert.equal(s.players[0].treasure,amount);
    assert.equal(s.players[0].bank,0);
    assert.ok(s.players[0].discard.includes(id));
    assert.deepEqual(s.destroyed,[]);
    s = applyAction(s,{type:"end"});
    assert.equal(s.players[0].treasure,amount);
    assert.ok(!("coin" in s.turn));
    assert.equal(cards[id].coin,undefined);
  });
}
test("treasure income observes capacity and can score at base without Energy", () => {
  let s = createGame({goal:50});
  s.players[0].hand = ["preciousCache"];
  s.players[0].treasure = 18;
  s = applyAction(s,{type:"play",index:0});
  assert.equal(s.players[0].treasure,20);
  s = applyAction(s,{type:"bank"});
  assert.equal(s.players[0].bank,20);
  assert.equal(s.turn.movement,0);
  assert.equal(s.players[0].treasure,0);
});
test("older saves merge remaining Coin into carried treasure within capacity", () => {
  const s=createGame();
  s.players[0].treasure=18;
  s.turn.coin=5;
  const loaded=loadGame({version:5,state:s});
  assert.equal(loaded.players[0].treasure,20);
  assert.ok(!("coin" in loaded.turn));
  assert.deepEqual(loadGame({version:6,state:loaded}),loaded);
  assert.equal(s.turn.coin,5);
});

test("treasure generated by an income card is lost on defeat", () => {
  let s = createGame();
  const tile=Object.values(s.board.tiles).find(t=>t.type === "black");
  s.players[0].hand=["preciousCache"];
  s = applyAction(s,{type:"play",index:0});
  s.players[0].position=tile.vertices[0];
  s.turn.movement=1;
  s = applyAction(s,{type:"enter",tile:tile.id});
  s = applyAction(s,{type:"resolveCombat"});
  assert.equal(s.active,1);
  assert.equal(s.players[0].treasure,0);
  assert.ok([...s.players[0].hand,...s.players[0].deck,...s.players[0].discard].includes("preciousCache"));
});
